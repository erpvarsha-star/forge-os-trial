/**
 * five-s-challenge-generator
 *
 * Generates one 5S housekeeping challenge for today by calling OpenRouter (google/gemma-4-31b-it:free),
 * and writes it to the "5s_challenges" table (quoted — table name starts
 * with a digit) in the shape app/(worker)/5s.tsx actually reads: one row
 * per day (unique on `date`), no per-department rows — the app's own
 * query never filters by department, just `.eq('date', today)`.
 *
 * Intended to run once daily (cron), early morning, before the first shift.
 * Idempotent: upserts on `date`, safe to re-run.
 */

import { handleOptions, jsonResponse } from '../_shared/cors.ts';
import { supabaseAdmin } from '../_shared/supabaseAdmin.ts';
import { istDateStr } from '../_shared/istDate.ts';

interface ChallengeJson {
  challenge_en: string;
  challenge_hi: string;
  category: 'Sort' | 'Set' | 'Shine' | 'Standardise' | 'Sustain';
  verification_hint_en: string;
  verification_hint_hi: string;
}

const PROMPT =
  'You are a 5S workplace organiser for an Indian forging plant with departments: Forge Shop, Press Shop, Heat Treatment, Machine Shop. ' +
  'Generate today\'s 5S challenge. Return only valid JSON: {"challenge_en": "max 20 words", "challenge_hi": "max 20 words in Hindi", ' +
  '"category": "Sort|Set|Shine|Standardise|Sustain", "verification_hint_en": "what photo should show", "verification_hint_hi": "same in Hindi"}';

// Free OpenRouter pools are shared and saturate unpredictably (429 upstream_provider_shared_pool).
// OpenRouter's `models` fallback retries the next model on any error, rate-limiting included,
// which keeps the daily cron from silently skipping a day. Order is Hindi quality first, and the
// list deliberately spans different upstream providers.
// HARD LIMIT: OpenRouter caps `models` at 3 items (undocumented; returns HTTP 400
// "'models' array must have 3 items or fewer"), so never add a fourth entry. The three are
// deliberately on three different upstream providers because one provider's shared free pool
// saturating is the actual failure mode this chain exists to survive.
const MODELS = [
  'google/gemma-4-31b-it:free',             // best free Hindi (140+ languages); Google AI Studio pool
  'nvidia/nemotron-3-ultra-550b-a55b:free', // NVIDIA pool — different upstream, 550B
  'baidu/ernie-5.5-flash-preview:free',     // Baidu pool — third distinct upstream, last resort
];

async function generateChallengeFromOpenRouter(): Promise<ChallengeJson> {
  const apiKey = Deno.env.get('OPENROUTER_API_KEY');
  if (!apiKey) throw new Error('OPENROUTER_API_KEY is not set');

  const res = await fetch('https://openrouter.ai/api/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey}`,
      'HTTP-Referer': 'https://github.com/erpvarsha-star/forge-os-trial',
      'X-Title': 'Forge OS',
    },
    body: JSON.stringify({
      model: MODELS[0],
      models: MODELS,
      reasoning: { effort: 'none' },   // this JSON is ~120 tokens; thinking would eat the whole budget (see max_tokens below)
      messages: [{ role: 'user', content: PROMPT }],
      // Belt-and-braces: reasoning tokens count against this cap, so even if a model ignores
      // effort 'none' there is room left for the ~120-token JSON answer.
      max_tokens: 800,
      response_format: { type: 'json_object' },
    }),
  });

  if (!res.ok) {
    throw new Error(`OpenRouter API error ${res.status}: ${await res.text()}`);
  }

  const data = await res.json();
  console.log('5S challenge generated by', data?.model ?? 'unknown');
  const text: string | undefined = data?.choices?.[0]?.message?.content;
  if (!text) {
    // OpenRouter can answer HTTP 200 with a non-completion body (e.g. an {"error": {...}} payload),
    // so surface the error object and a truncated raw snapshot instead of discarding the body.
    const apiErr = data?.error;
    const errDetail = apiErr
      ? `error.code=${apiErr.code ?? 'unknown'} error.message=${apiErr.message ?? 'unknown'}`
      : 'error=none';
    let snapshot: string;
    try {
      snapshot = JSON.stringify(data) ?? String(data);
    } catch {
      snapshot = '[unserialisable response body]';
    }
    if (snapshot.length > 600) snapshot = snapshot.slice(0, 600) + '...[truncated]';
    const detail =
      `OpenRouter returned no content (model=${data?.model ?? 'unknown'}, finish_reason=${data?.choices?.[0]?.finish_reason ?? 'unknown'}, ${errDetail}, body=${snapshot})`;
    console.error(detail);
    throw new Error(detail);
  }

  // Some models wrap JSON in a ```json ... ``` fence — strip it before parsing.
  const cleaned = text.trim().replace(/^```json\s*/i, '').replace(/^```\s*/i, '').replace(/```$/i, '').trim();
  return JSON.parse(cleaned) as ChallengeJson;
}

Deno.serve(async (req: Request) => {
  const preflight = handleOptions(req);
  if (preflight) return preflight;

  const db = supabaseAdmin();
  const today = istDateStr();

  try {
    const challenge = await generateChallengeFromOpenRouter();

    const { error: insertError } = await db.from('5s_challenges').upsert(
      {
        date: today,
        challenge_text_en: challenge.challenge_en,
        challenge_text_hi: challenge.challenge_hi,
        department: null, // one plant-wide challenge per day — matches app/(worker)/5s.tsx's query
      },
      { onConflict: 'date' }
    );

    if (insertError) return jsonResponse({ error: insertError.message }, 500);

    return jsonResponse({ date: today, challenge });
  } catch (err) {
    console.error('five-s-challenge-generator failed', err);
    return jsonResponse({ error: err instanceof Error ? err.message : 'Internal error' }, 500);
  }
});
