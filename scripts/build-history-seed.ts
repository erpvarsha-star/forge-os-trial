/**
 * Build PATCH_90 SQL: seed Apr–Sep 2026 as ARCHIVED pay runs with immutable
 * pay_run_items from the legacy salary workbooks (ACTUAL paid amounts — never
 * recalculated).
 *
 * Input: payroll_history_apr_sep_2026.json (NOT committed to git — salary data).
 * Usage:  npx tsx scripts/build-history-seed.ts path/to/payroll_history.json > scripts/PATCH_90_history_seed.sql
 * A human reviews the SQL, then runs it in the Supabase SQL editor.
 * Requires PATCH_89 applied first (pay_periods/pay_runs/pay_run_items).
 * Employees are matched by employees.emp_code — unknown codes are skipped and
 * reported on stderr, never silently dropped.
 */
import * as fs from 'fs';

const file = process.argv[2];
if (!file) { console.error('usage: npx tsx scripts/build-history-seed.ts <history.json>'); process.exit(1); }
const hist = JSON.parse(fs.readFileSync(file, 'utf8'));

const MONTH_NAMES: Record<number, string> = { 4: 'April', 5: 'May', 6: 'June', 7: 'July', 8: 'August', 9: 'September' };
const sql = (s: string) => String(s).replace(/'/g, "''");

console.log(`-- PATCH_90 — historical payroll seed (Apr–Sep 2026, ACTUAL paid amounts).
-- Generated by scripts/build-history-seed.ts — do not hand-edit.
-- Requires PATCH_89. Idempotent: safe to re-run (on conflict do nothing).
`);

const skipped: string[] = [];
for (const [category, months] of Object.entries(hist.data as Record<string, Record<string, any[]>>)) {
  for (const [m, recs] of Object.entries(months)) {
    const month = Number(m), year = 2026;
    const label = `${MONTH_NAMES[month]} ${year}`;
    console.log(`-- ${label} / ${category}: ${recs.length} employees`);
    console.log(`insert into pay_periods (month, year, start_date, end_date, status)
  values ('${String(month).padStart(2, '0')}', '${year}', '${year}-${String(month).padStart(2, '0')}-01',
          ('${year}-${String(month).padStart(2, '0')}-01'::date + interval '1 month - 1 day')::date, 'locked')
  on conflict (month, year) do nothing;
insert into pay_runs (pay_period_id, name, status, note)
  select p.id, '${sql(label)} — ${sql(category)} (historical)', 'archived',
         'Seeded from legacy workbook; amounts are as actually paid.'
  from pay_periods p
  where p.month = '${String(month).padStart(2, '0')}' and p.year = '${year}'
    and not exists (select 1 from pay_runs x where x.pay_period_id = p.id
                    and x.name = '${sql(label)} — ${sql(category)} (historical)');
`);
    for (const rec of recs) {
      const net = Number(rec.net ?? 0);
      if (!net) { skipped.push(`${label}/${rec.emp} (no net)`); continue; }
      const snapshot = JSON.stringify({
        category, worked: rec.worked ?? null,
        earnings: pickEarnings(rec, category), deductions: pickDeductions(rec, category),
        totalEarnings: rec.total_earning ?? rec.gross ?? null,
        totalDeductions: rec.gross_ded ?? rec.total_ded ?? null,
        netPay: net, otPay: rec.ot_amount ?? 0, otHours: rec.ot_hours ?? null,
        employer: { pf: rec.er_pf ?? 0, bonus: rec.bonus ?? 0, gratuity: rec.gratuity ?? 0 },
        historical: true,
      }).replace(/'/g, "''");
      console.log(`insert into pay_run_items (pay_run_id, employee_id, snapshot, net_pay)
select r.id, e.id, '${snapshot}'::jsonb, ${net}
from pay_runs r
join pay_periods p on p.id = r.pay_period_id and p.month = '${String(month).padStart(2, '0')}' and p.year = '${year}'
join employees e on e.emp_code = '${sql(rec.emp)}'
where r.name = '${sql(label)} — ${sql(category)} (historical)'
on conflict (pay_run_id, employee_id) do nothing;`);
    }
    console.log('');
  }
}
if (skipped.length) console.error('SKIPPED (no net paid):', skipped.join(', '));

function pickEarnings(r: any, cat: string): Record<string, number> {
  const n = (v: any) => (v == null || v === '' ? undefined : Number(v));
  const base: Record<string, any> = cat === 'PERMANENT_WORKER'
    ? { BASIC: n(r.basic), HRA: n(r.hra), CONVEYANCE: n(r.conv), WASHING: n(r.wash), EDUCATION: n(r.edu), HEAT: n(r.heat), VDA: n(r.vda), PROD_ALLOWANCE: n(r.prod) }
    : cat === 'STAFF'
      ? { BASIC: n(r.basic), HRA: n(r.hra), CONVEYANCE: n(r.conv), MEDICAL: n(r.medical), EDUCATION: n(r.edu), PRO_DEV: n(r.pro_dev), COMMUNICATION: n(r.communication), UNIFORM: n(r.uniform), WASHING: n(r.washing) }
      : { GROSS: n(r.gross) };
  if (n(r.ot_amount)) base.OT = n(r.ot_amount);
  if (n(r.arrears)) base.ARREARS = n(r.arrears);
  return Object.fromEntries(Object.entries(base).filter(([, v]) => v !== undefined));
}
function pickDeductions(r: any, cat: string): Record<string, number> {
  const n = (v: any) => (v == null || v === '' ? undefined : Number(v));
  const out: Record<string, any> = {};
  if (cat === 'STAFF' || cat === 'PERMANENT_WORKER') {
    out.PF = n(r.pf); out.ESI = n(r.esi); out.PT = n(r.pt); out.MLWF = n(r.mlwf);
  }
  if (n(r.tds)) out.TDS = n(r.tds);
  if (n(r.canteen)) out.CANTEEN = n(r.canteen);
  if (n(r.society)) out.SOCIETY = n(r.society);
  if (n(r.advance)) out.ADVANCE = n(r.advance);
  if (n(r.other_ded)) out.OTHER = n(r.other_ded);
  if (n(r.prod_offset)) out.PROD_OFFSET = n(r.prod_offset);
  return Object.fromEntries(Object.entries(out).filter(([, v]) => v !== undefined && v !== 0));
}
