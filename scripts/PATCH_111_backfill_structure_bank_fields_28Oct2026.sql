-- WHY: The pay-run export action (and the bank-file CSV) picks each employee's
-- NEWEST salary-structure row with effective_from <= period end. Read-only
-- verification 28 Oct found 14 rows with effective_from >= 2026-07-26 that are
-- missing one or more bank fields (several generated by the salary-change
-- approval flow, which does not capture bank details). For those employees the
-- October bank file would show blank bank cells even though an older row has
-- the data. Affected codes observed: VFL1557, VFL1560, VFL1567, VFL5272,
-- VFL5397, VFL5398, VFL5399, VFL5400, VFL5405, VFL5446, VFL5458, VFL5463,
-- VFL5465, VFL5466 (re-check with the preview query below before applying;
-- the UPDATE is written defensively and only fills NULLs).
-- WHAT: For every structure row missing bank fields, copy the missing values
-- from the SAME employee's own older row that has them. NULLs with no donor
-- row stay NULL (new hires genuinely lack bank data until HR enters it).
-- RULES KEPT: additive/data-fix only, no deletes, engine untouched, no
-- personal values written into this file (the SQL derives them at run time).
-- ============================================================================

-- ---------------------------------------------------------------------------
-- STEP 1 (run first): preview what WOULD be filled, per employee code.
-- Expect ~14 rows (some fields may have no donor and stay blank — those are
-- the employees HR must enter bank details for manually).
-- ---------------------------------------------------------------------------
SELECT e.emp_code,
       t.effective_from,
       t.bank_name IS NULL AS missing_bank_name,
       t.account_no  IS NULL AS missing_account_no,
       t.ifsc        IS NULL AS missing_ifsc
FROM employee_salary_structure t
JOIN employees e ON e.id = t.employee_id
WHERE t.effective_from >= DATE '2026-07-26'
  AND (t.bank_name IS NULL OR t.account_no IS NULL OR t.ifsc IS NULL)
ORDER BY e.emp_code, t.effective_from;

-- ---------------------------------------------------------------------------
-- STEP 2 (after review): apply the backfill inside a transaction so it can be
-- rolled back if the preview surprised you.
-- ---------------------------------------------------------------------------
BEGIN;

UPDATE employee_salary_structure t
SET bank_name = COALESCE(t.bank_name, (
      SELECT s.bank_name FROM employee_salary_structure s
      WHERE s.employee_id = t.employee_id
        AND s.effective_from < t.effective_from
        AND s.bank_name IS NOT NULL
      ORDER BY s.effective_from DESC LIMIT 1)),
    account_no = COALESCE(t.account_no, (
      SELECT s.account_no FROM employee_salary_structure s
      WHERE s.employee_id = t.employee_id
        AND s.effective_from < t.effective_from
        AND s.account_no IS NOT NULL
      ORDER BY s.effective_from DESC LIMIT 1)),
    ifsc = COALESCE(t.ifsc, (
      SELECT s.ifsc FROM employee_salary_structure s
      WHERE s.employee_id = t.employee_id
        AND s.effective_from < t.effective_from
        AND s.ifsc IS NOT NULL
      ORDER BY s.effective_from DESC LIMIT 1))
WHERE (t.bank_name IS NULL OR t.account_no IS NULL OR t.ifsc IS NULL)
  AND t.effective_from >= DATE '2026-07-26';

-- STEP 3: verify — should return 0 rows if every fillable NULL got a donor.
-- Any rows remaining here need HR to enter bank details (no older row had them).
SELECT e.emp_code, t.effective_from,
       t.bank_name IS NULL AS still_missing_bank_name,
       t.account_no  IS NULL AS still_missing_account_no,
       t.ifsc        IS NULL AS still_missing_ifsc
FROM employee_salary_structure t
JOIN employees e ON e.id = t.employee_id
WHERE t.effective_from >= DATE '2026-07-26'
  AND (t.bank_name IS NULL OR t.account_no IS NULL OR t.ifsc IS NULL)
ORDER BY e.emp_code;

